"""Planner: turns a form description into a Python program + values.

The program is plain Python source executed by the integration inside
Pyodide (WASM) on the page. It receives two globals:

    DOM   -- the DOM snapshot the integration sent
    VALUES-- the answers to fill in

and must define `fill(page)` where `page` is a small helper object the
integration injects (page.set(selector, value), page.click(selector), ...).

Programs come from two sources:
  1. The rulebook (answers.jsonc) — deterministic, no LLM.
  2. An LLM provider — writes the program when no rule matches.
"""
from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

from .form_adapters import detect_site
from .llm import BaseProvider

SYSTEM_PROMPT = """You write small Python programs that fill web forms.
You will be given a JSON description of a form (fields with labels, types,
options, selectors). Write Python that defines a function:

    def fill(page, VALUES):
        ...

`page` is a helper with methods:
    page.set(selector, value)      # set text / value of an input
    page.click(selector)           # click an element (radio/checkbox/next)
    page.select(selector, value)   # pick an option in a <select>
    page.submit()                  # submit the form

`VALUES` is a dict mapping field labels (lowercased) to answers.
Rules:
- Only use selectors from the description.
- Fields whose description has a non-empty "value" are ALREADY filled by
  the user: do NOT touch them — skip set/click/select for those entirely.
- For radio/checkbox, `page.click` the selector of the matching option.
- Move through multi-step forms with page.click on next buttons.
- Output ONLY the Python source, no markdown fences, no explanation.
"""


class Planner:
    def __init__(self, rulebook: dict[str, Any] | None = None,
                 provider: BaseProvider | None = None) -> None:
        self.rulebook = rulebook or {}
        self.provider = provider

    # -- rulebook -----------------------------------------------------------
    def lookup_answers(self, site: str, url: str) -> dict[str, Any] | None:
        rules = self.rulebook.get("rules", [])
        for rule in rules:
            if rule.get("site") and rule["site"] != site:
                continue
            if rule.get("urlPattern") and not re.search(rule["urlPattern"], url):
                continue
            if rule.get("site") or rule.get("urlPattern"):
                return rule.get("values", {})
        return None

    # -- program generation ---------------------------------------------------
    def plan(self, description: dict[str, Any]) -> dict[str, Any]:
        site = description.get("site", "generic")
        url = description.get("url", "")
        values = self.lookup_answers(site, url)
        if values is None:
            values = self.rulebook.get("defaults", {})

        program = self._rule_program(description, values)
        if program is None and self.provider is not None:
            program = self._llm_program(description)

        if program is None:
            program = self._rule_program(description, values, force=True)

        return {"program": program, "values": values, "site": site}

    def _rule_program(self, description: dict, values: dict,
                      force: bool = False) -> str | None:
        """Deterministic template program built from the description."""
        fields = description.get("fields", [])
        if not fields and not force:
            return None
        lines = [
            "# generated by BrowserStonks rulebook",
            "def fill(page, VALUES):",
        ]
        body: list[str] = []
        for f in fields:
            sel = f.get("selector") or ""
            label = (f.get("label") or "").lower().strip()
            ftype = f.get("type", "text")
            key = f'VALUES.get("{label}")'
            if not label:
                continue
            # Respect text the user already wrote: never generate a set()
            # for a field that already has content. radio/checkbox/select
            # still get filled; force-override with "force": true.
            if f.get("value") and ftype not in ("radio", "checkbox", "select"):
                if not f.get("force"):
                    continue
            if ftype in ("radio", "checkbox"):
                body.append(f"    v = {key}")
                body.append(f"    if v: page.click({sel!r})")
            elif ftype == "select":
                body.append(f"    v = {key}")
                body.append(f"    if v: page.select({sel!r}, v)")
            else:
                body.append(f"    v = {key}")
                body.append(f"    if v: page.set({sel!r}, v)")
        if not body:
            body.append("    pass  # no recognizable fields")
        return "\n".join(lines + body)

    def _llm_program(self, description: dict) -> str:
        user = json.dumps(description, indent=2)
        out = self.provider.complete(SYSTEM_PROMPT, user)
        out = out.strip()
        if out.startswith("```"):
            out = re.sub(r"^```[a-zA-Z]*\n?|\n?```$", "", out)
        return out


def load_rulebook(path: Path) -> dict[str, Any]:
    if not path.exists():
        return {}
    from .config import loads_jsonc
    return loads_jsonc(path.read_text())
